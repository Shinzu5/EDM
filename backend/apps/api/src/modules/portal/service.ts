/**
 * Patient portal — self-scoped views for the PATIENT role.
 *
 * - records: own patient + encounters + RELEASED lab results + claims + consents
 * - results/:id/download: requires RELEASED status + own patient + granted
 *   DATA_SHARING consent; serves a presigned S3 URL when S3_BUCKET is set,
 *   else a locally generated synthetic PDF data-URL. Writes an audit row.
 * - consent: list + toggle (consentType/granted).
 */
import { GetObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { prisma, type Patient } from '@medidata/db';
import type { Request } from 'express';
import { z } from 'zod';
import { config } from '../../config.js';
import { ApiError } from '../../lib/envelope.js';
import { resolvePatientForUser } from '../../lib/patientScope.js';
import { pdfDataUrl } from '../../lib/pdf.js';
import { dec } from '../../lib/serialize.js';
import { writeAudit } from '../../middleware/audit.js';

export const ConsentToggleSchema = z.object({
  consentType: z.string().trim().min(1).max(64),
  granted: z.boolean(),
});

async function ownPatient(req: Request): Promise<Patient> {
  const patient = await resolvePatientForUser(req.auth!);
  if (!patient) throw new ApiError(404, 'NO_PATIENT_LINK', 'No patient record is linked to this account');
  return patient;
}

export async function records(req: Request): Promise<Record<string, unknown>> {
  const patient = await ownPatient(req);
  const [encounters, labResults, claims, consents] = await Promise.all([
    prisma.encounter.findMany({ where: { patientId: patient.id }, orderBy: { admittedAt: 'desc' } }),
    prisma.labResult.findMany({
      where: { patientId: patient.id, status: { in: ['RELEASED', 'CORRECTED'] } },
      orderBy: { collectedAt: 'desc' },
    }),
    prisma.claim.findMany({
      where: { patientId: patient.id },
      orderBy: { submittedAt: 'desc' },
      include: { payer: { select: { name: true, code: true } } },
    }),
    prisma.consent.findMany({ where: { patientId: patient.id }, orderBy: { grantedAt: 'desc' } }),
  ]);
  writeAudit(req, {
    action: 'GET /api/portal/records',
    entityType: 'portalRecords',
    entityId: patient.id,
  });
  return {
    patient: { id: patient.id, mrn: patient.mrn, firstName: patient.firstName, lastName: patient.lastName, dateOfBirth: patient.dateOfBirth, sex: patient.sex, email: patient.email, city: patient.city },
    encounters,
    labResults,
    claims: claims.map((c) => ({ ...c, billedAmount: dec(c.billedAmount), paidAmount: dec(c.paidAmount) })),
    consents,
  };
}

export async function downloadResult(req: Request, resultId: string): Promise<Record<string, unknown>> {
  const patient = await ownPatient(req);
  const result = await prisma.labResult.findUnique({ where: { id: resultId } });
  if (!result || result.patientId !== patient.id) {
    // 404 (not 403) to avoid exposing which result ids exist.
    throw new ApiError(404, 'NOT_FOUND', `Lab result ${resultId} not found`);
  }
  if (!['RELEASED', 'CORRECTED'].includes(result.status)) {
    throw new ApiError(409, 'RESULT_NOT_RELEASED', `Result is in status ${result.status}; only RELEASED/CORRECTED results can be downloaded`);
  }
  const consent = await prisma.consent.findFirst({
    where: { patientId: patient.id, consentType: 'DATA_SHARING', granted: true },
  });
  if (!consent) {
    throw new ApiError(403, 'CONSENT_REQUIRED', 'A granted DATA_SHARING consent is required to download results');
  }

  const key = `results/${patient.mrn}/${result.id}.pdf`;
  let downloadUrl: string;
  let mode: string;
  if (config.S3_BUCKET) {
    const s3 = new S3Client({
      region: config.S3_REGION,
      ...(config.AWS_S3_ENDPOINT ? { endpoint: config.AWS_S3_ENDPOINT, forcePathStyle: true } : {}),
    });
    downloadUrl = await getSignedUrl(s3, new GetObjectCommand({ Bucket: config.S3_BUCKET, Key: key }), {
      expiresIn: 30 * 60,
    });
    mode = 'presigned-s3';
  } else {
    downloadUrl = pdfDataUrl(`Laboratory Result — ${result.testCode}`, [
      { text: `Patient: ${patient.firstName} ${patient.lastName} (MRN ${patient.mrn})`, bold: true },
      { text: `Test: ${result.testCode}` },
      { text: `Value: ${result.valueNumeric ?? result.valueText ?? 'n/a'} ${result.unit}` },
      { text: `Reference range: ${result.referenceRange}` },
      { text: `Abnormal flag: ${result.abnormalFlag ?? 'none'}` },
      { text: `Collected: ${result.collectedAt.toISOString()}` },
      { text: `Resulted: ${result.resultedAt?.toISOString() ?? 'n/a'}` },
      { text: `Released: ${result.releasedAt?.toISOString() ?? 'n/a'}` },
      { text: '' },
      { text: 'SYNTHETIC DATA — generated by MediData demo (no S3 configured).', size: 8 },
    ]);
    mode = 'synthetic-data-url';
  }

  // Explicit audit row for the download (deck: secure result delivery).
  writeAudit(req, {
    action: 'GET /api/portal/results/:id/download',
    entityType: 'labResult',
    entityId: result.id,
    afterJson: { patientId: patient.id, mode, key },
  });

  return {
    resultId: result.id,
    fileName: `${result.testCode}-${result.id}.pdf`,
    mode,
    expiresInMinutes: mode === 'presigned-s3' ? 30 : null,
    downloadUrl,
  };
}

export async function listConsents(req: Request): Promise<unknown[]> {
  const patient = await ownPatient(req);
  return prisma.consent.findMany({ where: { patientId: patient.id }, orderBy: { grantedAt: 'desc' } });
}

export async function toggleConsent(req: Request, body: z.infer<typeof ConsentToggleSchema>): Promise<unknown> {
  const patient = await ownPatient(req);
  const now = new Date();
  const existing = await prisma.consent.findFirst({ where: { patientId: patient.id, consentType: body.consentType } });
  if (existing) {
    return prisma.consent.update({
      where: { id: existing.id },
      data: {
        granted: body.granted,
        grantedAt: body.granted ? now : existing.grantedAt,
        revokedAt: body.granted ? null : now,
      },
    });
  }
  return prisma.consent.create({
    data: {
      patientId: patient.id,
      consentType: body.consentType,
      granted: body.granted,
      grantedAt: now,
      revokedAt: body.granted ? null : now,
    },
  });
}
